// Helper to generate realistic candles for interactive charts
export function generateCandlesForAsset(currentPrice: number, timeframe: '1D' | '1W' | '1M' | '3M' | '1Y'): Candle[] {
  const points = timeframe === '1D' ? 36 : timeframe === '1W' ? 42 : timeframe === '1M' ? 30 : timeframe === '3M' ? 45 : 52;
  const candles: Candle[] = [];
  
  const now = Date.now();
  const stepMs = timeframe === '1D' ? 10 * 60 * 1000 : timeframe === '1W' ? 4 * 3600 * 1000 : 24 * 3600 * 1000;
  
  // Backtrack from current price
  let runningClose = currentPrice;
  const tempPrices: number[] = [runningClose];
  
  const volatility = currentPrice > 1000 ? currentPrice * 0.012 : currentPrice * 0.018;

  for (let i = 1; i < points; i++) {
    const delta = (Math.random() - 0.49) * volatility;
    runningClose = Math.max(runningClose - delta, currentPrice * 0.6);
    tempPrices.unshift(runningClose);
  }

  for (let i = 0; i < points; i++) {
    const timeDate = new Date(now - (points - 1 - i) * stepMs);
    const close = tempPrices[i];
    const prev = i > 0 ? tempPrices[i - 1] : close * 0.998;
    const open = prev;
    const spread = Math.abs(close - open) + Math.random() * (volatility * 0.4);
    const high = Math.max(open, close) + Math.random() * (spread * 0.5);
    const low = Math.min(open, close) - Math.random() * (spread * 0.5);
    const volume = Math.floor(10000 + Math.random() * 50000);

    const timeStr = timeframe === '1D' 
      ? timeDate.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : timeDate.toLocaleDateString([], { month: 'short', day: 'numeric' });

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  return candles;
}

